#!/usr/bin/env node
import { existsSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
process.chdir(root)
const packages = new Map()
// pnpm's lockfile installs runtime and build packages together; include both sets of notices.
for (const entry of readdirSync('node_modules/.pnpm', { withFileTypes: true })) {
  const modules = join('node_modules/.pnpm', entry.name, 'node_modules')
  if (!entry.isDirectory() || !existsSync(modules)) continue
  for (const item of readdirSync(modules)) {
    const paths = item.startsWith('@')
      ? readdirSync(join(modules, item)).map(name => join(modules, item, name))
      : [join(modules, item)]
    for (const path of paths) {
      const manifest = join(path, 'package.json')
      if (!existsSync(manifest)) continue
      const metadata = JSON.parse(readFileSync(manifest, 'utf8'))
      packages.set(`npm:${metadata.name}@${metadata.version}`, {
        directory: realpathSync(path),
        license: typeof metadata.license === 'string' ? metadata.license : metadata.license?.type,
        repository: typeof metadata.repository === 'string' ? metadata.repository : metadata.repository?.url,
      })
    }
  }
}
const cargo = spawnSync('cargo', ['metadata', '--format-version', '1', '--locked', '--manifest-path', 'src-tauri/Cargo.toml'], { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 })
if (cargo.status !== 0) {
  process.stderr.write(cargo.stderr)
  process.exit(cargo.status ?? 1)
}
for (const item of JSON.parse(cargo.stdout).packages.filter(item => item.source)) {
  packages.set(`cargo:${item.name}@${item.version}`, {
    directory: dirname(item.manifest_path), license: item.license,
    repository: item.repository, licenseFile: item.license_file,
  })
}
const sections = ['Generated by scripts/collect-licenses.mjs from installed, locked dependencies. Do not edit manually.\nIncludes frontend runtime/build dependencies and Cargo packages for all supported targets.']
const texts = new Map()
for (const [name, item] of [...packages].sort(([left], [right]) => left.localeCompare(right, 'en'))) {
  const files = readdirSync(item.directory, { withFileTypes: true })
    .filter(entry => entry.isFile() && /^(licen[sc]e|copying|notice)([._-]|$)/i.test(entry.name))
    .map(entry => entry.name)
  if (item.licenseFile && !files.includes(item.licenseFile)) files.push(item.licenseFile)
  sections.push(`\n${'='.repeat(72)}\n${name}\nLicense: ${item.license ?? 'See bundled license text'}\nSource: ${item.repository ?? (name.startsWith('cargo:') ? `https://crates.io/crates/${name.slice(6).split('@')[0]}` : `https://www.npmjs.com/package/${name.slice(4).split('@').slice(0, -1).join('@')}`)}\n`)
  for (const file of files.sort()) {
    const text = readFileSync(join(item.directory, file), 'utf8').trim()
    const hash = createHash('sha256').update(text).digest('hex')
    if (!texts.has(hash)) texts.set(hash, { id: texts.size + 1, text })
    sections.push(`${basename(file)}: license text ${texts.get(hash).id}`)
  }
}
for (const { id, text } of texts.values()) sections.push(`\n${'='.repeat(72)}\nLicense text ${id}\n\n${text}\n`)
writeFileSync('Resources/ThirdPartyNotices/dependencies-LICENSES.txt', sections.join('\n') + '\n')
console.log(`已收集 ${packages.size} 个依赖的许可声明。`)
